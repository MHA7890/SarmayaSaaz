dates = []
actuals = []

for line in raw_text.strip().split('\n'):
    if not line.strip() or 'Release date' in line:
        continue
    # A standard line looks like: Jul 31, 2026 (Jul)\t06:30\t49.2\t50.1
    # or Sep 01, 2014\t06:00\t51.1\t51.2
    # Check if the line has tabs and starts with a month (3 letters)
    match = re.match(r'([A-Z][a-z]{2}\s\d{2},\s\d{4})', line)
    if match:
        date_str = match.group(1)
        # the rest of the line is tab separated
        parts = line.split('\t')
        if len(parts) >= 3:
            actual = parts[2].strip()
            if actual:
                dates.append(date_str)
                actuals.append(actual)

df = pd.DataFrame({'Date': pd.to_datetime(dates), 'China_PMI': actuals})
df.set_index('Date', inplace=True)
df.sort_index(inplace=True)
df.to_csv('./data/china_pmi.csv')
print("Saved China PMI data to data/china_pmi.csv")
print(df.head())
